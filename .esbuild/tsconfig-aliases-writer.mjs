/**
 * Shared read/write helpers for tsconfig.aliases.json.
 *
 * tsconfig.aliases.json has two distinct sections, each owned by a different
 * script. This module is the single place that knows the file path, the key
 * classification rules, and the output format — so neither script can
 * accidentally clobber the other's section.
 *
 * Section 1 — Component aliases   (@moodle/lms/* and @moodle-original/lms/*)
 *   Owned by: grunt jsconfig  →  generate-aliases.mjs
 *
 * Section 2 — Swizzle theme aliases  (@moodle-<theme>/lms/*)
 *   Owned by: grunt swizzle:manifest  →  generate-swizzle-manifest.mjs
 *
 * @copyright  2026 Moodle Pty Ltd <hello@moodle.com>
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */

import fs from 'fs';
import path from 'path';

export const TSCONFIG_ALIASES_PATH = path.join(process.cwd(), 'tsconfig.aliases.json');

const HEADER = [
    '// WARNING: Do not edit this file manually.',
    '// Section 1 — Component aliases     — generated by `grunt jsconfig`.',
    '// Section 2 — Swizzle theme aliases — generated by `grunt swizzle:manifest`.',
].join('\n');

const SECTION_JSCONFIG = '      // ── Component aliases (grunt jsconfig) ' + '─'.repeat(42);
const SECTION_SWIZZLE  = '      // ── Swizzle theme aliases (grunt swizzle:manifest) ' + '─'.repeat(29);

/**
 * True when the key belongs to the jsconfig section.
 * Matches @moodle/lms/* and @moodle-original/lms/* only.
 *
 * @param {string} key
 * @returns {boolean}
 */
export function isJsconfigKey(key) {
    return key.startsWith('@moodle/lms/') || key.startsWith('@moodle-original/lms/');
}

/**
 * True when the key belongs to the swizzle section.
 * Matches @moodle-<theme>/lms/* where theme is not "original".
 *
 * @param {string} key
 * @returns {boolean}
 */
export function isSwizzleKey(key) {
    return key.startsWith('@moodle-') && !key.startsWith('@moodle-original/lms/');
}

/**
 * Read tsconfig.aliases.json and split its paths into the two sections.
 *
 * Returns empty objects when the file does not exist or cannot be parsed,
 * so callers can always proceed to a merge + write without special-casing.
 *
 * @returns {{ jsconfigPaths: Record<string, string[]>, swizzlePaths: Record<string, string[]> }}
 */
export function readExistingAliases() {
    if (!fs.existsSync(TSCONFIG_ALIASES_PATH)) {
        return {jsconfigPaths: {}, swizzlePaths: {}};
    }
    try {
        const content = fs.readFileSync(TSCONFIG_ALIASES_PATH, 'utf8');
        const stripped = content.replace(/^\uFEFF/, '').replace(/^\s*\/\/.*$/gm, '');
        const parsed = JSON.parse(stripped);
        const allPaths = parsed?.compilerOptions?.paths ?? {};

        /** @type {Record<string, string[]>} */
        const jsconfigPaths = {};
        /** @type {Record<string, string[]>} */
        const swizzlePaths = {};

        for (const [key, val] of Object.entries(allPaths)) {
            if (isJsconfigKey(key)) {
                jsconfigPaths[key] = val;
            } else if (isSwizzleKey(key)) {
                swizzlePaths[key] = val;
            }
        }
        return {jsconfigPaths, swizzlePaths};
    } catch {
        return {jsconfigPaths: {}, swizzlePaths: {}};
    }
}

/**
 * Serialize a paths value array.
 * Single-element → compact one-liner. Multi-element → indented multiline.
 *
 * @param {string[]} val
 * @returns {string}
 */
function serializeValue(val) {
    if (val.length === 1) {
        return `["${val[0]}"]`;
    }
    const inner = val.map(v => `        "${v}"`).join(',\n');
    return `[\n${inner}\n      ]`;
}

/**
 * Write tsconfig.aliases.json with both sections clearly separated.
 *
 * Each call replaces the full file. The caller is responsible for passing
 * the preserved section it did not regenerate (obtained via readExistingAliases).
 *
 * @param {Record<string, string[]>} jsconfigPaths  Section 1 entries.
 * @param {Record<string, string[]>} swizzlePaths   Section 2 entries.
 * @returns {void}
 */
export function writeTsconfigAliases(jsconfigPaths, swizzlePaths) {
    const jsconfigEntries = Object.entries(jsconfigPaths);
    const swizzleEntries  = Object.entries(swizzlePaths);
    const hasSwizzle = swizzleEntries.length > 0;

    const pathLines = [SECTION_JSCONFIG];

    jsconfigEntries.forEach(([key, val], i) => {
        const isLast = i === jsconfigEntries.length - 1;
        const comma = (!isLast || hasSwizzle) ? ',' : '';
        pathLines.push(`      ${JSON.stringify(key)}: ${serializeValue(val)}${comma}`);
    });

    pathLines.push('');
    pathLines.push(SECTION_SWIZZLE);

    if (!hasSwizzle) {
        pathLines.push('      // (run `grunt swizzle:manifest` to populate)');
    } else {
        swizzleEntries.forEach(([key, val], i) => {
            const comma = i < swizzleEntries.length - 1 ? ',' : '';
            pathLines.push(`      ${JSON.stringify(key)}: ${serializeValue(val)}${comma}`);
        });
    }

    const content = [
        HEADER,
        '{',
        '  "compilerOptions": {',
        '    "paths": {',
        '',
        ...pathLines,
        '',
        '    }',
        '  }',
        '}',
        '',
    ].join('\n');

    fs.writeFileSync(TSCONFIG_ALIASES_PATH, content);
}
